import './timeline.check.mjs';
import assert from 'node:assert/strict';
import {Session,SESSION_FORMAT_VERSION} from '@deepseek-ai/dsh-session';
import {branchAsAssistant,branchAsUser,locate,locateForRead} from './core.js';
const events=[];
const add=(type,data,surfaceOp)=>{events.push({type,data,seq:events.length,time:1,...(surfaceOp?{surfaceOp}:{})});};
const source={kind:'model',provider:'fixture',model:'model'};
add('turn/start',{turn:1});
add('step/start',{turn:1,step:1});
add('request/header',{header:{config:{provider:'fixture',model:'model'}},reason:'initial'});
add('user/message',{id:'u',role:'user',source:{kind:'user'},content:[{type:'text',text:'Test a tool task'}]},'append');
add('assistant/message',{turn:1,step:1,stream:[],message:{id:'a-tool',role:'assistant',source,content:[{type:'tool-call',id:'call',name:'fixture_tool',arguments:'{}'}]}},'append');
add('tool/call',{turn:1,step:1,callId:'call',name:'fixture_tool',arguments:'{}'});
add('tool/result',{turn:1,step:1,message:{id:'tool-result',role:'tool',source:{kind:'tool',callId:'call'},toolCallId:'call',content:[{type:'text',text:'real tool result'}]}},'append');
add('step/end',{turn:1,step:1});
add('step/start',{turn:1,step:2});
add('assistant/message',{turn:1,step:2,stream:[],message:{id:'a-final',role:'assistant',source,content:[{type:'text',text:'Original final reply'}]}},'append');
add('step/end',{turn:1,step:2});
add('turn/end',{turn:1,reason:{kind:'completed'}});
const snapshot={events,session:{id:'source'}};
const before=structuredClone(snapshot);
let saved,uid=0,created=0,rerunRequest,submitted=[];
const deps={readSession:async()=>snapshot,uuid:()=>`tool-fixture-${++uid}`,create:async q=>{
 created++;rerunRequest=q;
 const session=Session.create(q.sessionId,q.seed,{version:SESSION_FORMAT_VERSION,id:q.sessionId,createdAt:1,...q.meta},q.inheritedEventCount);
 return {agent:{session,inbox:{nextTurn:[],nextStep:[]},followup:m=>submitted.push(m)},dispose:async()=>{}};
},flush:async session=>{saved=JSON.parse(JSON.stringify({events:session.snapshotEvents(),header:session.header,count:session.inheritedEventCount}));return true;}};
const result=await branchAsAssistant(deps,'source','a-final','你好','Original final reply');
assert.equal(result.ok,true);
const restored=Session.fromRestore(result.sessionId,saved.events,saved.header,saved.count,'detached');
assert.equal(restored.deriveMessages().at(-1).role,'assistant');
assert.deepEqual(restored.deriveMessages().at(-1).content,[{type:'text',text:'你好'}]);
assert.deepEqual(saved.events.slice(0,9),events.slice(0,9));
const marker=saved.events.find(e=>e.type==='last-word/version');
assert.equal(marker.ignorable,true);
assert.equal(marker.data.sessionId,result.sessionId);
assert.equal(marker.data.effect.operation,'edit-reply');
assert.equal(marker.data.effect.targetTurn,1);
assert.equal(marker.data.effect.before,'Original final reply');
assert.equal(marker.data.effect.after,'你好');
assert.equal(marker.data.inverse.sessionId,'source');
assert.equal(saved.events.filter(e=>e.type==='tool/call').length,1);
assert.equal(saved.events.find(e=>e.type==='tool/result').data.message.content[0].text,'real tool result');
assert.deepEqual(submitted,[]);
assert.deepEqual(snapshot,before);
await assert.rejects(()=>branchAsAssistant(deps,'source','a-tool','Replacement',''),/工具调用/);
assert.equal(created,1);
const retry=await branchAsUser(deps,'source','a-final',undefined,undefined,undefined,'retry');
assert.equal(retry.ok,true);
assert.equal(rerunRequest.seed.length,2);
assert.equal(rerunRequest.seed[0].type,'session/end-seed');
assert.equal(rerunRequest.seed[1].type,'last-word/version');
assert.equal(rerunRequest.seed[1].ignorable,true);
assert.equal(rerunRequest.seed[1].data.effect.operation,'retry');
assert.equal(rerunRequest.seed[1].data.effect.targetTurn,1);
assert.equal(rerunRequest.inheritedEventCount,0);
const retryRestored=Session.fromRestore(retry.sessionId,JSON.parse(JSON.stringify(rerunRequest.seed)),{version:SESSION_FORMAT_VERSION,id:retry.sessionId,createdAt:1,...rerunRequest.meta},rerunRequest.inheritedEventCount);
assert.deepEqual(retryRestored.deriveMessages(),[]);
assert.equal(submitted.length,1);
assert.notEqual(submitted[0].id,'u');
assert.deepEqual(submitted[0].content,events[3].data.content);
const createFailed={...deps,create:async()=>{throw new Error('fixture creation failed');}};
const failedEdit=await branchAsAssistant(createFailed,'source','a-final','New reply','Original final reply');
assert.equal(failedEdit.ok,false);assert.equal(failedEdit.sessionId,undefined);assert.match(failedEdit.error,/creation failed/);
const failedRetry=await branchAsUser(createFailed,'source','a-final',undefined,undefined,undefined,'retry');
assert.equal(failedRetry.ok,false);assert.equal(failedRetry.sessionId,undefined);assert.match(failedRetry.error,/creation failed/);
const assistantEvent=(id,content)=>[{type:'assistant/message',seq:0,time:1,surfaceOp:'append',data:{turn:1,step:1,message:{id,role:'assistant',source,content}}}];
const readBack=locateForRead(assistantEvent('r-only',[{type:'reasoning',text:'思考过程'}]),'r-only');
assert.equal(readBack.field,'reasoning');
assert.equal(readBack.text,'思考过程');
assert.throws(()=>locate(assistantEvent('r-only',[{type:'reasoning',text:'思考过程'}]),'r-only'),/没有可编辑的文字/);
assert.equal(locateForRead(assistantEvent('t-only',[{type:'text',text:'正文'}]),'t-only').field,'text');
assert.throws(()=>locateForRead(assistantEvent('empty',[]),'empty'),/没有可编辑的文字/);
console.log('Tool-task checks passed: final reply edit, historical tools, rerun cut, Agent creation failures and reasoning-only read fallback.');
